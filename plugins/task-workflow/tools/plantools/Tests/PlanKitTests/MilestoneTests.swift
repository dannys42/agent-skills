import Foundation
import Testing
@testable import PlanKit

private let fixture = try! String(contentsOf: URL(fileURLWithPath: #filePath).deletingLastPathComponent()
    .appendingPathComponent("Fixtures/Roadmap-Milestones.md"), encoding: .utf8)

private func edited(_ pairs: [(String, String)]) -> String {
    pairs.reduce(fixture) { text, pair in
        precondition(text.contains(pair.0), "fixture lacks \(pair.0)")
        return text.replacingOccurrences(of: pair.0, with: pair.1)
    }
}

private func list(_ name: String, _ tasks: String, completed: Bool = false, age: Double = 0) -> NextStep.File {
    NextStep.File(name: name, text: "# Tasklist\n\n## G1 Gate\n\n" + tasks, completed: completed, modified: Date(timeIntervalSince1970: age))
}

private func decide(_ text: String = fixture, overview: Bool = true, lists: [NextStep.File] = []) -> NextStep {
    NextStep.decide(.init(docDir: "docs", hasOverview: overview, roadmap: Roadmap(text: text), tasklists: lists))
}

private let openStd = "- [ ] T1 Do it\n  - Model: standard (Sonnet 5.5)\n"
private let done = "- [x] T1 Did it\n  - Model: standard (Sonnet 5.5)\n"
private let l2Open = list("Tasklist-L2-Grid.md", openStd)
private let l2Moved = list("Tasklist-L2-Grid.md", done, completed: true)
private let l3Listed = list("Tasklist-L3-Text.md", openStd)
private let allDone = [("[in progress]", "[done]"), ("enough? [planned]", "enough? [done]"), ("- L6", "- X6")]

@Suite("Roadmap milestones")
struct RoadmapMilestoneTests {
    @Test func parsesMilestoneLinesAndSubBullets() {
        let r = Roadmap(text: fixture)
        #expect(r.milestones.map(\.id) == ["M1", "M2", "M3"])
        #expect(r.milestones.map(\.status) == ["current", "planned", "planned"])
        #expect(r.milestones.map(\.mark) == ["owner", "proposed", "proposed"])
        let m1 = r.milestones[0]
        #expect(m1.name == "print a puzzle" && m1.outcome == "I can print a playable 9×9 Sudoku from the app.")
        #expect(m1.touches == ["Document_App", "Grid_View"] && m1.exit?.hasPrefix("File > Print") == true)
        #expect(r.milestones[1].additiveCheck?.hasPrefix("yes") == true && r.milestones[2].touches.isEmpty)
        #expect(r.currentMilestone?.id == "M1" && m1.close == nil)
        let closing = Roadmap(text: edited([("  - Exit: File", "  - Close: awaiting demo (2026-11-01)\n  - Exit: File")]))
        #expect(closing.milestones[0].close == "awaiting demo (2026-11-01)")
    }

    @Test func readsTouchesMilestoneTagsAndTheEscalationMarker() throws {
        let r = Roadmap(text: edited([("Class: shape\n\n### L3", "Class: shape\nEscalation: 2026-11-01\n- Grid API differs\n\n### L3")]))
        #expect(r.touches(of: "L3") == ["Grid_View", "Print_Export"])
        #expect(r.ladder.map { r.milestone(of: $0) } == [nil, "M1", "M1", "M1", "M2"])
        #expect(r.escalation(of: "L2") == "2026-11-01" && r.escalation(of: "L3") == nil)
        #expect(r.lint().isEmpty)
    }

    @Test func namesRungsAndMilestonesFromHeadingsOrQuestions() {
        let r = Roadmap(text: fixture)
        #expect(r.named("L2") == "L2 (Draw a fixed 9x9 grid)")
        #expect(r.named("l3") == "L3 (Control text in the grid)")
        #expect(r.named("L1") == "L1 (Can I build and run the most basic document-based macOS app?)")
        #expect(r.named("L6") == "L6 (Can the generator remove cells so one solution remains?)")
        #expect(r.named("M2") == "M2 (any size)")
        #expect(r.named("L9") == nil && r.named("M9") == nil)
    }

    @Test func mapGroupsRungsUnderTheirMilestoneWithStatusAndTouches() {
        let map = Roadmap(text: fixture).map(source: "Roadmap-Milestones.md")
        #expect(map.hasPrefix("# Map: Sudoku printer\n\nGenerated by `roadmap map` from Roadmap-Milestones.md"))
        #expect(map.contains("## M1 (print a puzzle) [current]\n\nI can print a playable 9×9 Sudoku from the app. `owner`\nTouches: Document_App, Grid_View\nExit: File > Print"))
        #expect(map.contains("- L2 (Draw a fixed 9x9 grid) [in progress] — Touches: Grid_View\n- L3 (Control text in the grid) [planned] — Touches: Grid_View, Print_Export\n- L6 (Can the generator remove cells so one solution remains?) [horizon]\n"))
        #expect(map.contains("## M3 (puzzle library) [planned]\n\nI can keep the puzzles I made and print them again. `proposed`\n\nNo rungs yet."))
        #expect(map.contains("## Rungs without a milestone\n\n- L1 (Can I build"))
        #expect(map.hasSuffix("\n"))
    }

    @Test func mapOfAnOldRoadmapIsOneListOfRungs() {
        let map = Roadmap(text: "# Roadmap: X\n\n## Ladder\n\n1. L1 — a [done]\n2. L2 — b [planned]\n").map(source: "Roadmap-X.md")
        #expect(map == "# Map: X\n\nGenerated by `roadmap map` from Roadmap-X.md; do not edit by hand.\n\n- L1 (a) [done]\n- L2 (b) [planned]\n")
    }

    @Test func lintFlagsMalformedMilestonesAndUnknownTags() {
        let r = Roadmap(text: edited([("- M3 (puzzle library) — I can keep", "- M3 puzzle library — I can keep"), ("Milestone: M1\nTouches: Grid_View, Print", "Milestone: M7\nTouches: Grid_View, Print")]))
        let messages = r.lint().map(\.message)
        #expect(messages.contains { $0.hasPrefix("milestone line is not in the format") })
        #expect(messages.contains("L3 names milestone M7, which is not in ## Milestones"))
    }

    @Test func lintFlagsAnInProgressOrEscalatedRungOutsideTheCurrentMilestone() {
        let r = Roadmap(text: edited([("Milestone: M1\nTouches: Grid_View\n", "Milestone: M2\nTouches: Grid_View\nEscalation: 2026-11-01\n"),
                                      ("Milestone: M1\nTouches: Grid_View, Print", "Milestone: M2\nTouches: Grid_View, Print")]))
        let messages = r.lint().map(\.message)
        #expect(messages.contains("L2 is in progress but belongs to M2, which is not the current milestone; roadmap next never routes it"))
        #expect(!messages.contains { $0.hasPrefix("L3 ") })
        let escalated = Roadmap(text: edited([("[in progress]", "[done]"), ("Milestone: M1\nTouches: Grid_View\n", "Milestone: M2\nTouches: Grid_View\nEscalation: 2026-11-01\n")]))
        #expect(escalated.lint().map(\.message) == ["L2 carries an Escalation marker but belongs to M2, which is not the current milestone; roadmap next never routes it"])
    }
}

@Suite("NextStep milestones")
struct NextStepMilestoneTests {
    @Test func milestonePlanWhenAPlannedRungOfTheCurrentMilestoneHasNoTasklist() {
        let s = decide(lists: [l2Open])
        #expect(s.step == "milestone-plan" && s.model == "opus" && s.milestone == "M1" && s.rung == nil)
        #expect(s.command == "/roadmap-plan-next-rung plan M1")
        #expect(s.why == "M1 (print a puzzle): L3 (Control text in the grid) has no tasklist")
        #expect(s.rendered.hasPrefix("step: milestone-plan\nmilestone: M1\nmodel: opus"))
    }

    @Test func milestonePlanTakesPrecedenceOverEscalationAndCompletedListsCount() {
        let escalated = edited([("Class: shape\n\n### L3", "Class: shape\nEscalation: 2026-11-01\n\n### L3")])
        #expect(decide(escalated, lists: [l2Moved]).step == "milestone-plan")
        #expect(decide(escalated, lists: [l2Moved, list("Tasklist-L3-Text.md", openStd, completed: true)]).step == "escalation")
    }

    @Test func escalationWhenTheRungCarriesTheMarker() {
        let text = edited([("Class: shape\n\n### L3", "Class: shape\nEscalation: 2026-11-01\n- Grid API differs\n\n### L3")])
        let s = decide(text, lists: [l2Moved, l3Listed])
        #expect(s.step == "escalation" && s.model == "opus" && s.rung == "L2" && s.command == "/roadmap-plan-next-rung escalation L2")
        #expect(s.why == "L2 (Draw a fixed 9x9 grid): the automatic fold-back escalated on 2026-11-01")
    }

    @Test func runsTheInProgressRungsOpenListOnTheOrchestratorModel() {
        let s = decide(lists: [l2Open, l3Listed])
        #expect(s.step == "run" && s.rung == "L2" && s.model == "sonnet" && s.list == "docs/Tasklist-L2-Grid.md")
        #expect(s.command == "/rung run L2" && s.why == "L2 (Draw a fixed 9x9 grid): Tasklist-L2-Grid.md has 1 open task(s)")
        let user = decide(lists: [list("Tasklist-L2-Grid.md", "- [ ] T5 USER — Confirm\n"), l3Listed])
        #expect(user.step == "user" && user.why == "L2 (Draw a fixed 9x9 grid): USER tasks waiting: T5")
    }

    @Test func aClosedRungListStillInTheDocDirReentersTheFoldBack() {
        let s = decide(lists: [list("Tasklist-L2-Grid.md", done), l3Listed])
        #expect(s.step == "run" && s.rung == "L2" && s.model == "sonnet" && s.list == "docs/Tasklist-L2-Grid.md")
        #expect(s.why.contains("fold-back did not finish"))
        // A closed tidy list is not a rung list, so it is no unfinished fold-back.
        #expect(decide(lists: [l2Moved, list("Tasklist-L2-Tidy.md", done), l3Listed]).step == "escalation")
    }

    @Test func anInProgressRungWithEveryListMovedButNotDoneIsAnEscalation() {
        let s = decide(lists: [l2Moved, l3Listed])
        #expect(s.step == "escalation" && s.model == "opus" && s.rung == "L2" && s.why.hasSuffix("the fold-back did not set it done"))
    }

    @Test func horizonOrDeferredItemsOfTheCurrentMilestoneMeanReplanNotCloseOrPlanning() {
        let horizon = decide(edited([("[in progress]", "[done]"), ("enough? [planned]", "enough? [done]")]))
        #expect(horizon.step == "replan" && horizon.model == "opus" && horizon.milestone == "M1")
        #expect(horizon.why == "no planned rung in M1 (print a puzzle); horizon: L6 (Can the generator remove cells so one solution remains?); bring one back, detail one, or drop them")
        let deferred = decide(edited(allDone + [("enough? [done]", "enough? [deferred: waits on M2]")]))
        #expect(deferred.step == "replan" && deferred.why.contains("deferred: L3 (Control text in the grid)"))
    }

    @Test func aCurrentMilestoneWithNoRungsIsReplanned() {
        let s = decide(edited(allDone + [("[current]", "[done]"), ("Size_Picker [planned]", "Size_Picker [current]"), ("- L7", "- X7")]))
        #expect(s.step == "replan" && s.milestone == "M2" && s.why == "M2 (any size) has no rungs; add the rungs that reach its outcome")
    }

    @Test func theNextPlannedRungRunsWhenNoneIsInProgress() {
        let s = decide(edited([("[in progress]", "[done]")]), lists: [l2Moved, l3Listed])
        #expect(s.step == "run" && s.rung == "L3" && s.list == "docs/Tasklist-L3-Text.md")
    }

    @Test func openMilestoneAndRefactorListsRunBeforeClose() {
        let s = decide(edited(allDone), lists: [list("Tasklist-M1-Fixes.md", openStd)])
        #expect(s.step == "run" && s.rung == nil && s.milestone == "M1" && s.command == "/tasklist-run docs/Tasklist-M1-Fixes.md")
        #expect(decide(edited(allDone), lists: [list("Tasklist-Refactor-Parser.md", openStd)]).list == "docs/Tasklist-Refactor-Parser.md")
    }

    @Test func milestoneCloseWhenEveryRungIsFinishedAndResumesFromTheCloseLine() {
        let s = decide(edited(allDone), lists: [list("Tasklist-M1-Fixes.md", done, completed: true)])
        #expect(s.step == "milestone-close" && s.model == "opus" && s.milestone == "M1" && s.command == "/roadmap-plan-next-rung milestone-close M1")
        #expect(s.why == "every rung of M1 (print a puzzle) is finished and no fix or follow-up list is open")
        let paused = decide(edited(allDone + [("  - Exit: File", "  - Close: awaiting demo (2026-11-01)\n  - Exit: File")]))
        #expect(paused.step == "milestone-close" && paused.why.hasSuffix("the close resumes after: awaiting demo (2026-11-01)"))
    }

    @Test func replanWhenNoMilestoneIsCurrentAndFinishedWhenAllAreDone() {
        let between = decide(edited(allDone + [("[current]", "[done]")]))
        #expect(between.step == "replan" && between.milestone == "M2" && between.why == "no current milestone; M2 (any size) is the next planned one")
        let over = decide(edited(allDone + [("[current]", "[done]"), ("Size_Picker [planned]", "Size_Picker [done]"),
                                            ("`proposed` [planned]", "`proposed` [dropped]"), ("- L7", "- X7")]))
        #expect(over.step == "finished" && over.command == "/risk-first-roadmap")
    }

    @Test func designWhenTheRoadmapHasMilestonesButNoSystemDesign() {
        let s = decide(overview: false, lists: [l2Open])
        #expect(s.step == "design" && s.model == "opus")
    }

    @Test func anOldFormatRoadmapKeepsThePerRungRoutes() {
        let old = "## Ladder\n\n1. L1 — a [done]\n2. L2 — b [planned]\n"
        #expect(decide(old).step == "plan" && decide(old).command == "/rung plan L2")
        let closing = decide("## Ladder\n\n1. L1 — a [in progress]\n", lists: [list("Tasklist-L1-A.md", done)])
        #expect(closing.step == "close" && closing.milestone == nil)
    }

    @Test func milestoneRoutesNameTheirSkill() {
        #expect(Predictions.skillName("/roadmap-plan-next-rung plan M1") == "roadmap-plan-next-rung")
        for route in ["milestone-plan", "escalation", "milestone-close"] {
            #expect(Predictions.skillName("/rung \(route)") == "roadmap-plan-next-rung")
        }
    }
}
